export const LANGS = ['fr', 'en'];

// Langue de l'accueil : ?lang=en, sinon le dernier choix, sinon celle du téléphone.
export function pickLang() {
  const asked = new URLSearchParams(location.search).get('lang');
  if (LANGS.includes(asked)) return asked;
  try { const saved = localStorage.getItem('ctt-lang'); if (LANGS.includes(saved)) return saved; } catch { /* navigation privée */ }
  return /^fr\b/i.test(navigator.language || '') ? 'fr' : 'en';
}
export function saveLang(lang) { try { localStorage.setItem('ctt-lang', lang); } catch { /* navigation privée */ } }

