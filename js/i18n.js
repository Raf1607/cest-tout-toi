export const DICT = { fr: FR, en: EN };

export function tr(lang) {
  const d = DICT[lang] || FR;
  return (key, ...args) => {
    const v = d[key] ?? FR[key];
    return typeof v === 'function' ? v(...args) : v;
  };
}
